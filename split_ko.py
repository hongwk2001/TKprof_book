    if b.startswith('__LITERAL__'):
        out_paras.append(b.replace('__LITERAL__', ''))
        continue
    
    pos = text.find(b)
    if pos == -1:
        with open('error.txt', 'w', encoding='utf-8') as err_f:
            err_f.write(f"Error at {idx+1}: '{b}' not found!")
        break
    pos += len(b)
    out_paras.append(text[:pos].strip())
    text = text[pos:].strip()

